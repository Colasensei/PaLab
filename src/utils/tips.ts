function shuffledPool(pool: string[]): () => string {
  let idx = 0;
  let arr: string[] = [];
  const shuffle = () => {
    arr = [...pool];
    for (let i = arr.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [arr[i], arr[j]] = [arr[j], arr[i]];
    }
    idx = 0;
  };
  shuffle();
  return () => {
    if (idx >= arr.length) shuffle();
    return arr[idx++];
  };
}

